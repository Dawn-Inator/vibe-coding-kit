// Sync the kit's Claude Code role definitions (templates/claude-agents/vck-*.md) into a consuming
// project's .claude/agents/. A role definition pins the worker's model and tool allowlist, so rules that
// used to be restated in every dispatch prompt travel with the role, and a read-only role really has no
// write tools.
//
// Ownership: only files that carry the generated marker are managed. A project's own agent files,
// including one that happens to use the vck- prefix, are never overwritten or removed; they are reported
// as conflicts instead. Roles follow the orchestration skill: excluding agent-orchestration-guardrails in
// project.config.json removes the generated roles on the next sync.

import { existsSync, lstatSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { writeTextAtomically } from '../lib/atomic-write.mjs';

export const ROLE_SOURCE_DIR = 'templates/claude-agents';
export const ROLE_TARGET_DIR = '.claude/agents';
export const ROLE_FILE_RE = /^vck-[a-z0-9]+(?:-[a-z0-9]+)*\.md$/;
export const GATING_SKILL = 'agent-orchestration-guardrails';
const MARKER_PREFIX = '<!-- Generated by vibe-coding-kit from templates/claude-agents/';

export function markerFor(name) {
  return `${MARKER_PREFIX}${name}. Edit the kit source; skills sync overwrites this file. -->`;
}

export function isGenerated(text) {
  return typeof text === 'string' && text.includes(MARKER_PREFIX);
}

/** Split a role file into its frontmatter fields and body. Throws on a missing or malformed block. */
export function parseRole(name, source) {
  const text = String(source).replace(/\r\n?/g, '\n');
  const match = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) throw new Error(`${name}: role definition must start with a frontmatter block`);
  const fields = {};
  for (const line of match[1].split('\n')) {
    const field = line.match(/^([A-Za-z][\w-]*):\s*(.*?)\s*$/);
    if (field) fields[field[1]] = field[2].replace(/^(["'])(.*)\1$/, '$2');
  }
  return { frontmatter: match[0], fields, body: text.slice(match[0].length).replace(/^\n+/, '') };
}

/** Tools listed in a role's `tools:` field, in order. */
export function roleTools(fields) {
  return String(fields.tools ?? '')
    .split(',')
    .map((tool) => tool.trim())
    .filter(Boolean);
}

export function renderRole(name, source) {
  const { frontmatter, fields, body } = parseRole(name, source);
  if (`${fields.name}.md` !== name) throw new Error(`${name}: frontmatter name must equal the file name`);
  if (!fields.model || fields.model === 'inherit') throw new Error(`${name}: a kit role must pin a model`);
  return `${frontmatter}\n${markerFor(name)}\n\n${body}`;
}

export function rolesEnabled(projectConfig) {
  return projectConfig?.skills?.skills?.[GATING_SKILL]?.mode !== 'exclude';
}

/** Map of role file name to the exact content the project should hold. */
export function expectedRoles(kitRoot, projectConfig) {
  const dir = join(resolve(kitRoot), ROLE_SOURCE_DIR);
  const roles = new Map();
  if (!rolesEnabled(projectConfig) || !existsSync(dir)) return roles;
  for (const name of readdirSync(dir).filter((entry) => ROLE_FILE_RE.test(entry)).sort()) {
    roles.set(name, renderRole(name, readFileSync(join(dir, name), 'utf8')));
  }
  return roles;
}

function symlinkedComponent(projectRoot) {
  let path = projectRoot;
  for (const part of ROLE_TARGET_DIR.split('/')) {
    path = join(path, part);
    if (!existsSync(path)) return null;
    if (lstatSync(path).isSymbolicLink()) return path;
  }
  return null;
}

function generatedTargets(targetDir) {
  if (!existsSync(targetDir)) return [];
  return readdirSync(targetDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && ROLE_FILE_RE.test(entry.name))
    .map((entry) => entry.name)
    .filter((name) => isGenerated(readFileSync(join(targetDir, name), 'utf8')))
    .sort();
}

/**
 * Write (or, with checkOnly, compare) the generated role definitions.
 * Returns { ok, problems, written, removed, roles }. Never writes through a symlinked .claude or
 * .claude/agents directory, and never touches a file without the generated marker.
 */
export function syncRoleDefinitions({ projectRoot, kitRoot, projectConfig, checkOnly = false }) {
  const root = resolve(projectRoot);
  const targetDir = join(root, ROLE_TARGET_DIR);
  const expected = expectedRoles(kitRoot, projectConfig);
  const problems = [];
  let written = 0;
  let removed = 0;

  const linked = symlinkedComponent(root);
  if (linked) {
    problems.push(`conflict: ${linked} is a symlink; role definitions are not written through it`);
    return { ok: false, problems, written, removed, roles: [...expected.keys()] };
  }

  for (const [name, content] of expected) {
    const path = join(targetDir, name);
    const rel = `${ROLE_TARGET_DIR}/${name}`;
    if (!existsSync(path)) {
      if (checkOnly) problems.push(`missing: ${rel}`);
      else {
        writeTextAtomically(path, content);
        written += 1;
      }
      continue;
    }
    if (!lstatSync(path).isFile()) {
      problems.push(`conflict: ${rel} is not a regular file; the kit does not replace it`);
      continue;
    }
    const actual = readFileSync(path, 'utf8');
    if (!isGenerated(actual)) {
      problems.push(`conflict: ${rel} exists and is not kit-generated; rename or remove it to receive the kit role`);
      continue;
    }
    if (actual === content) continue;
    if (checkOnly) problems.push(`stale: ${rel}`);
    else {
      writeTextAtomically(path, content);
      written += 1;
    }
  }

  for (const name of generatedTargets(targetDir)) {
    if (expected.has(name)) continue;
    if (checkOnly) problems.push(`unexpected: ${ROLE_TARGET_DIR}/${name}`);
    else {
      rmSync(join(targetDir, name), { force: true });
      removed += 1;
    }
  }

  return { ok: problems.length === 0, problems, written, removed, roles: [...expected.keys()] };
}
