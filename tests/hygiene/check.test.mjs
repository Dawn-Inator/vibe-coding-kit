import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkHygiene, writeBaseline, GROWTH_ENV } from '../../src/hygiene/check.mjs';

const cli = fileURLToPath(new URL('../../cli.mjs', import.meta.url));
const META = { owner: 'platform', expiry: '2099-01-01', issue: 'ARCH-1', removal_plan: 'clear one package per iteration' };
const CLEAN = `package app

import (
	"context"
	"fmt"
)

type Store struct{ db DB }

func NewStore(db DB) (*Store, error) {
	if db == nil {
		return nil, fmt.Errorf("store: db is required")
	}
	return &Store{db: db}, nil
}

func (s *Store) Load(ctx context.Context, id string) (string, error) {
	v, err := s.db.Get(ctx, id)
	if err != nil {
		return "", fmt.Errorf("load %s: %w", id, err)
	}
	return v, nil
}
`;
const SMELLY = `package app

import (
	"context"
	"reflect"

	"example.com/app/internal/database/orders"
)

var ErrConfig = error(nil)

type Runtime struct{ dep any }

func (r *Runtime) Ready(ctx context.Context, a, b, c, d, e, f, g bool) error {
	defer func() { _ = recover() }()
	if r == nil || ctx == nil {
		return ErrConfig
	}
	if reflect.ValueOf(r.dep).IsNil() {
		return ErrConfig
	}
	if _, err := orders.Read(ctx); err != nil {
		return ErrConfig
	}
	if a || b || c || d || e || f || g {
		return nil
	}
	var m interface {
		ProtoReflect() interface{ GetUnknown() []byte }
	}
	_ = m.ProtoReflect().GetUnknown()
	return nil
}
`;
const NEW_DEBT = 'package service\n\nimport "context"\n\nfunc Do(ctx context.Context) bool { return ctx == nil }\n';

function fixture(t) {
  const root = mkdtempSync(path.join(os.tmpdir(), 'hygiene-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' });
  git('init', '-q', '-b', 'main');
  git('config', 'user.name', 'Test');
  git('config', 'user.email', 'test@example.com');
  const put = (name, data) => {
    const file = path.join(root, name);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, data);
  };
  const config = { schemaVersion: 1, include: ['internal/**/*.go'], exclude: ['**/*_test.go'], baseRef: 'main', lineLengthMax: 100,
    compositionRoots: ['internal/bootstrap/**'], dataAccessImports: ['example.com/app/internal/database'] };
  const saveConfig = () => put('.vibe-coding/code-hygiene.json', JSON.stringify(config));
  saveConfig();
  put('internal/service/store.go', CLEAN);
  const commit = (message) => { git('add', '-A'); git('commit', '-q', '-m', message); };
  commit('seed');
  const baselinePath = path.join(root, '.vibe-coding/code-hygiene-baseline.json');
  return { root, put, git, commit, config, saveConfig, baselinePath,
    check: (options = {}) => checkHygiene({ projectRoot: root, env: {}, ...options }),
    write: (options = {}) => writeBaseline({ projectRoot: root, env: {}, metadata: META, ...options }),
    baseline: () => JSON.parse(readFileSync(baselinePath, 'utf8')) };
}

const failuresOf = (result) => result.failures.join('\n');

test('clean code passes with no baseline (zero-debt default)', t => {
  const f = fixture(t);
  const result = f.check();
  assert.equal(result.ok, true, failuresOf(result));
  assert.equal(result.filesScanned, 1);
  assert.deepEqual(result.totals, {});
});

test('every rule fires on the defensive sample; tests and generated code are out of scope', t => {
  const f = fixture(t);
  f.put('internal/bootstrap/runtime.go', SMELLY);
  f.put('internal/bootstrap/runtime_test.go', SMELLY);
  f.put('internal/gen/api.pb.go', '// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage gen\n\nfunc (r *R) X() bool { return r == nil }\n');
  f.put('internal/service/long.go', `package service\n\nvar s = "${'x'.repeat(120)}"\n`);
  f.put('internal/service/ugly.go', 'package service\nfunc  Ugly( ) {}\n');
  const result = f.check();
  assert.equal(result.ok, false);
  for (const rule of ['nil-context-check', 'nil-receiver-guard', 'reflect-nil-probe', 'scattered-recover', 'wide-condition',
    'collapsed-error', 'unknown-field-rejection', 'composition-root-data-access', 'gofmt', 'line-length']) {
    assert.ok(result.totals[rule] > 0, `${rule} should fire: ${JSON.stringify(result.totals)}`);
  }
  assert.equal(result.totals['collapsed-error'], 1, 'only the err-check return collapses the error');
  assert.equal(result.totals.gofmt, 1, 'the generated file is not format-checked');
  assert.ok(!/_test\.go|api\.pb\.go/.test(failuresOf(result)));
  assert.match(failuresOf(result), /internal\/bootstrap\/runtime\.go:16/);
});

test('ratchet: frozen debt passes, new debt fails, repaid debt must shrink the baseline', t => {
  const f = fixture(t);
  f.put('internal/bootstrap/runtime.go', SMELLY);
  f.write();
  f.commit('freeze debt');
  assert.equal(f.check().ok, true, failuresOf(f.check()));

  f.put('internal/service/extra.go', NEW_DEBT);
  assert.match(failuresOf(f.check()), /new nil-context-check\|internal\/service\/extra\.go\|Do/);
  assert.throws(() => f.write(), /refusing to grow the baseline/);

  f.put('internal/service/extra.go', 'package service\n');
  f.put('internal/bootstrap/runtime.go', SMELLY.replace('\tdefer func() { _ = recover() }()\n', ''));
  assert.match(failuresOf(f.check()), /stale baseline scattered-recover/);
  f.write();
  assert.ok(!f.baseline().debt.some((d) => d.rule === 'scattered-recover'));
  assert.equal(f.check().ok, true, failuresOf(f.check()));
});

test('a baseline grown in the same change fails against merge-base unless a reason is given', t => {
  const f = fixture(t);
  f.put('internal/bootstrap/runtime.go', SMELLY);
  f.write();
  f.commit('freeze debt');
  f.git('checkout', '-q', '-b', 'feature');
  f.put('internal/service/extra.go', NEW_DEBT);
  f.write({ env: { [GROWTH_ENV]: 'local override' } });
  f.commit('sneak debt in');
  assert.match(failuresOf(f.check()), /baseline grew versus merge-base: debt nil-context-check/);
  const approved = f.check({ env: { [GROWTH_ENV]: 'approved ARCH-2' } });
  assert.equal(approved.ok, true, failuresOf(approved));
  assert.match(approved.warnings.join('\n'), /approved ARCH-2/);
});

test('narrowing the scope counts as growth and collapsed scans fail', t => {
  const f = fixture(t);
  f.put('internal/bootstrap/runtime.go', SMELLY);
  f.write();
  f.commit('freeze debt');
  f.config.exclude.push('internal/bootstrap/**');
  f.saveConfig();
  assert.throws(() => f.write(), /scope exclude added/);
  f.config.include = ['nothing/**/*.go'];
  f.saveConfig();
  const failures = failuresOf(f.check());
  assert.match(failures, /scan matched no files/);
  assert.match(failures, /scan collapsed/);
});

test('baseline metadata is required and expiry is enforced', t => {
  const f = fixture(t);
  f.put('internal/bootstrap/runtime.go', SMELLY);
  assert.throws(() => writeBaseline({ projectRoot: f.root, env: {} }), /needs --owner, --expiry, --issue, --removal-plan/);
  f.write({ metadata: { ...META, expiry: '2020-01-01' } });
  f.commit('expired');
  assert.match(failuresOf(f.check()), /baseline expired on 2020-01-01/);
});

test('an exemption covers only its declared symbol', t => {
  const f = fixture(t);
  f.put('internal/api/interceptor.go', 'package api\n\nfunc Recover() { defer func() { _ = recover() }() }\n');
  f.write();
  const baseline = { ...f.baseline(), debt: [], total: 0,
    exemptions: [{ rule: 'scattered-recover', path: 'internal/api/interceptor.go', symbol: 'Recover', count: 1, reason: 'the single panic interceptor' }] };
  writeFileSync(f.baselinePath, JSON.stringify(baseline));
  f.commit('exempt interceptor');
  assert.equal(f.check().ok, true, failuresOf(f.check()));
  f.put('internal/api/handler.go', 'package api\n\nfunc Handle() { defer func() { _ = recover() }() }\n');
  assert.match(failuresOf(f.check()), /new scattered-recover\|internal\/api\/handler\.go\|Handle/);
});

test('CLI exposes check and write-baseline', t => {
  const f = fixture(t);
  f.put('internal/bootstrap/runtime.go', SMELLY);
  const run = (...args) => spawnSync(process.execPath, [cli, 'hygiene', ...args, '--project-root', f.root], { encoding: 'utf8' });
  const failed = run('check');
  assert.equal(failed.status, 1, failed.stderr);
  assert.equal(JSON.parse(failed.stdout).ok, false);
  const written = run('write-baseline', '--owner', 'platform', '--expiry', '2099-01-01', '--issue', 'ARCH-1', '--removal-plan', 'shrink');
  assert.equal(written.status, 0, written.stderr);
  f.commit('freeze');
  const passed = run('check');
  assert.equal(passed.status, 0, passed.stdout + passed.stderr);
});
