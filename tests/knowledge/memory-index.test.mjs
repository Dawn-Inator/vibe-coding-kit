function makeRepo() {
  const repoRoot = mkdtempSync(join(tmpdir(), 'memory-index-test-'));
  // canonical_source references need a real path in the repo.
  writeFileSync(join(repoRoot, 'README.md'), '# fixture repo\n');
  const memoryRoot = join(repoRoot, '.vibe-coding', 'memory');
  mkdirSync(join(memoryRoot, 'general'), { recursive: true });
  mkdirSync(join(memoryRoot, 'workflow'), { recursive: true });
  return { repoRoot, memoryRoot };
}

function writeNote(memoryRoot, moduleName, stem, { frontmatter = {}, body = '' } = {}) {
  const fm = {
    name: stem,
    description: 'A test note description.',
    type: stem.startsWith('feedback_') ? 'feedback' : 'project',
    status: 'active',
    redaction: 'none',
    updated: '2026-01-01',
    canonical_source: stem.startsWith('feedback_') ? 'self' : 'README.md',
    ...frontmatter,
  };

  const lines = ['---'];
  for (const [key, value] of Object.entries(fm)) {
    if (value === undefined) continue;
    lines.push(`${key}: ${value}`);
  }
  lines.push('---');
  lines.push('');
  lines.push(body || 'Some body text explaining the lesson.');
  lines.push('');
  lines.push('**How to apply:** do the thing described above.');
  lines.push('');

  const filePath = join(memoryRoot, moduleName, `${stem}.md`);
  writeFileSync(filePath, lines.join('\n'), 'utf8');
  return filePath;
}

// ---------------------------------------------------------------------------
// 1. sync generates correctly formatted MEMORY.md / CATALOG.md
// ---------------------------------------------------------------------------

test('sync renders MEMORY.md and CATALOG.md with expected structure', () => {
  const { repoRoot, memoryRoot } = makeRepo();
  try {
    writeNote(memoryRoot, 'general', 'project_example_one', {
      frontmatter: { description: 'First example note.' },
    });
    writeNote(memoryRoot, 'workflow', 'feedback_example_two', {
      frontmatter: { description: 'Second example note.' },
    });

    const result = runSync(memoryRoot);
    assert.equal(result.notes.length, 2);
    assert.equal(result.wroteBootIndex, true);
    assert.equal(result.wroteCatalog, true);

    const bootIndex = readFileSync(join(memoryRoot, BOOT_INDEX_NAME), 'utf8');
    assert.match(bootIndex, /^<!-- GENERATED by scripts\/memory-index\.mjs\./);
    assert.match(bootIndex, /# Memory Index/);
    assert.match(bootIndex, /共 2 条，分布在 2 个模块/);
    assert.match(bootIndex, /### general\/ — .*（1）/);
    assert.match(bootIndex, /example_one/);
    assert.match(bootIndex, /### workflow\/ — .*（1）/);
    assert.match(bootIndex, /example_two/);

    const catalog = readFileSync(join(memoryRoot, CATALOG_NAME), 'utf8');
    assert.match(catalog, /^<!-- GENERATED by scripts\/memory-index\.mjs\./);
    assert.match(catalog, /# Memory Catalogue/);
    assert.match(catalog, /\[project_example_one\]\(general\/project_example_one\.md\)/);
    assert.match(catalog, /First example note\./);
    assert.match(catalog, /\[feedback_example_two\]\(workflow\/feedback_example_two\.md\)/);

    // Re-running sync with unchanged content should not rewrite.
    const second = runSync(memoryRoot);
    assert.equal(second.wroteBootIndex, false);
    assert.equal(second.wroteCatalog, false);
  } finally {
    rmSync(repoRoot, { recursive: true, force: true });
  }
});

