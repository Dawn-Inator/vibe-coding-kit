// 6. escapeTableCell escaping order
// ---------------------------------------------------------------------------

test('escapeTableCell escapes backslashes before pipes so a trailing backslash cannot swallow a pipe escape', () => {
  // If backslash-escaping ran AFTER pipe-escaping, this input's trailing
  // backslash would end up adjacent to (and effectively consume) the
  // following escaped pipe, letting a crafted description break out of its
  // table cell. Escaping backslashes first prevents that.
  const malicious = 'end of cell\\| injected | cell';
  const escaped = escapeTableCell(malicious);

  // Every literal backslash from the input must itself be escaped, and every
  // literal pipe must be escaped too — an attacker must not be able to
  // produce an unescaped `|` in the output.
  assert.equal(escaped, 'end of cell\\\\\\| injected \\| cell');
  assert.doesNotMatch(escaped.replace(/\\\\/g, ''), /(?<!\\)\|/);
});

test('escapeTableCell replaces newlines with spaces and trims', () => {
  assert.equal(escapeTableCell('  line one\nline two  '), 'line one line two');
});

