test('collectWikilinks finds real links and ignores fenced bash conditionals', () => {
  const body = [
    'See [[project_other_note]] for context.',
    '',
    '```bash',
    'if [[ -d "$DIR" ]]; then',
    '  echo hi',
    'fi',
    '```',
    '',
    'Also [[feedback_thing|display text]] with a pipe alias.',
  ].join('\n');

  const targets = collectWikilinks(body);
  assert.deepEqual(targets, ['project_other_note', 'feedback_thing']);
});

