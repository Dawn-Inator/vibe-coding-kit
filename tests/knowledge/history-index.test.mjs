test('escapeMarkdownLinkText escapes brackets and backslashes', () => {
  const input = 'Title with [brackets] and \\backslash';
  const escaped = escapeMarkdownLinkText(input);
  assert.equal(escaped, 'Title with \\[brackets\\] and \\\\backslash');
});

test('escapeTableCell escapes backslashes and pipes, collapsing whitespace', () => {
  const input = 'cell\\with|pipe   and   spaces';
  const escaped = escapeTableCell(input);
  assert.equal(escaped, 'cell\\\\with\\|pipe and spaces');
});

test('linkDestination percent-encodes spaces/brackets and escapes literal parentheses', () => {
  const dest = linkDestination('note (draft) [v2].md');
  assert.equal(dest, './note%20%28draft%29%20%5Bv2%5D.md');
});

