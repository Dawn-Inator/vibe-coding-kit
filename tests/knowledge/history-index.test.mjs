function git(repoRoot, args) {
  const result = spawnSync('git', withFixtureCommitIdentity(args), {
    cwd: repoRoot,
    encoding: 'utf8',
    env: isolatedFixtureGitEnv(),
  });
  if (result.status !== 0) {
    throw new Error(`git ${args.join(' ')} failed: ${result.stderr}`);
  }
  return result.stdout;
}

function makeGitRepo() {
  const repoRoot = mkdtempSync(join(tmpdir(), 'history-index-test-'));
  git(repoRoot, ['init', '-q']);

  // A tracked file directly referenced by related_files.
  writeFileSync(join(repoRoot, 'tracked-file.md'), '# tracked\n');

  // A tracked directory (a related_files entry can point at a directory,
  // considered tracked if any tracked path lives under it).
  mkdirSync(join(repoRoot, 'tracked-dir'), { recursive: true });
  writeFileSync(join(repoRoot, 'tracked-dir', 'inner.md'), '# inner\n');

  git(repoRoot, ['add', 'tracked-file.md', 'tracked-dir']);
  git(repoRoot, ['commit', '-q', '-m', 'seed fixture']);

  // A file that exists on disk but was never `git add`-ed.
  writeFileSync(join(repoRoot, 'untracked-file.md'), '# untracked\n');

  const historyRoot = join(repoRoot, '.vibe-coding', 'history');
  return { repoRoot, historyRoot };
}

function writeEntry(historyRoot, month, fileName, { frontmatter = {}, body } = {}) {
  const fm = {
    title: 'Example history entry',
    date: `${month}-15`,
    author: 'tester',
    purpose: 'Explain what happened in this entry.',
    category: 'general',
    scope: 'repo',
    status: 'done',
    related_files: ['tracked-file.md'],
    redaction: 'none',
    ...frontmatter,
  };

  const lines = ['---'];
  for (const [key, value] of Object.entries(fm)) {
    if (value === undefined) continue;
    if (Array.isArray(value)) {
      lines.push(`${key}:`);
      for (const item of value) lines.push(`  - ${item}`);
    } else {
      lines.push(`${key}: ${value}`);
    }
  }
  lines.push('---');
  lines.push('');
  lines.push(body !== undefined ? body : 'Body text describing what happened.');
  lines.push('');

  const dir = join(historyRoot, month);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, fileName), lines.join('\n'), 'utf8');
}

// ---------------------------------------------------------------------------
// 1. sync generates index.md with correct format; Summary column == purpose
// ---------------------------------------------------------------------------

test('sync renders index.md with a Summary column populated from "purpose"', () => {
  const { repoRoot, historyRoot } = makeGitRepo();
  try {
    writeEntry(historyRoot, '2026-01', '2026-01-15-example.md', {
      frontmatter: { title: 'My Title', purpose: 'This is the purpose text.' },
    });

    const results = runSync(historyRoot, ['2026-01']);
    assert.equal(results.length, 1);
    assert.equal(results[0].entryCount, 1);
    assert.equal(results[0].wrote, true);

    const indexContent = readFileSync(join(historyRoot, '2026-01', 'index.md'), 'utf8');
    assert.match(indexContent, /^# History Index - 2026-01/);
    assert.match(indexContent, /<!-- GENERATED by scripts\/history-index\.mjs\./);
    assert.match(indexContent, /\| Date \| Entry \| Category \| Scope \| Status \| Summary \|/);
    assert.match(indexContent, /\[My Title\]/);
    assert.match(indexContent, /This is the purpose text\./);

    // Re-sync with unchanged content should not rewrite.
    const second = runSync(historyRoot, ['2026-01']);
    assert.equal(second[0].wrote, false);
  } finally {
    rmSync(repoRoot, { recursive: true, force: true });
  }
});

